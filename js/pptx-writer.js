/*
 * pptx-writer.js — writes slide models from layout.js into an editable .pptx with PptxGenJS.
 * Every text box, option card and label is a separate, named PowerPoint object.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory(require('./latex.js'), require('./omml.js'));
  else root.QBWriter = factory(root.QBLatex, root.QBOmml);
})(typeof self !== 'undefined' ? self : this, function (QBLatex, QBOmml) {
  'use strict';

  const LAYOUT_NAME = 'QBANK_56x31_5';
  const MASTER_NAME = 'Question Slide';

  function runsToPptx(paragraphs, S, base) {
    const out = [];
    const paras = paragraphs && paragraphs.length ? paragraphs : [[{ text: ' ' }]];
    paras.forEach((runs, pi) => {
      const segs = [];
      (runs.length ? runs : [{ text: ' ' }]).forEach((r) => {
        QBLatex.scriptSegments(r).forEach((seg) => {
          const o = { fontFace: S.fonts[seg.kind] || S.fonts.lat };
          if (seg.kind === 'bn') o.lang = 'bn-BD';
          if (r.italic) o.italic = true;
          if (r.bold || base.bold) o.bold = true;
          if (r.sup) o.superscript = true;
          if (r.sub) o.subscript = true;
          segs.push({ text: seg.text, options: o });
        });
      });
      if (!segs.length) segs.push({ text: ' ', options: { fontFace: S.fonts.lat } });
      if (pi < paras.length - 1) segs[segs.length - 1].options.breakLine = true;
      out.push(...segs);
    });
    return out;
  }

  /**
   * deck: result of QBLayout.buildDeck
   * PptxGenJS: the constructor (window.PptxGenJS in the browser, require('pptxgenjs') in Node)
   * extras: { overlay: dataURI|null, title }
   */
  function writeDeck(deck, PptxGenJS, extras) {
    extras = extras || {};
    const S = deck.settings, T = deck.theme;
    const pres = new PptxGenJS();
    pres.defineLayout({ name: LAYOUT_NAME, width: S.slideW, height: S.slideH });
    pres.layout = LAYOUT_NAME;
    pres.title = extras.title || 'Question slides';
    pres.subject = 'Generated by QBank Slides';
    pres.theme = { headFontFace: S.fonts.bn, bodyFontFace: S.fonts.bn };

    const objects = [];
    if (extras.overlay) objects.push({ image: { x: 0, y: 0, w: S.slideW, h: S.slideH, data: extras.overlay } });
    pres.defineSlideMaster({ title: MASTER_NAME, background: { color: T.bg }, objects });

    const eqBoxes = {};
    let eqN = 0;
    const native = extras.nativeEquations !== false;

    for (const sm of deck.slides) {
      const slide = pres.addSlide({ masterName: MASTER_NAME });
      for (const el of sm.els) {
        if (el.kind === 'image') {
          slide.addImage({ data: el.data, x: el.x, y: el.y, w: el.w, h: el.h, objectName: el.name, altText: 'Question figure' });
          continue;
        }
        if (el.kind !== 'text') continue;
        const inset = el.inset || [0, 0, 0, 0]; // [top, right, bottom, left] in inches
        const opts = {
          x: el.x, y: el.y, w: el.w, h: el.h,
          fontSize: el.size, color: el.color, align: el.align || 'left', valign: el.valign || 'top',
          lineSpacingMultiple: el.spacing || S.lineSpacing,
          paraSpaceBefore: 0, paraSpaceAfter: 0,
          margin: [inset[3] * 72, inset[1] * 72, inset[2] * 72, inset[0] * 72], // pptxgenjs: [l, r, b, t] in points
          fontFace: S.fonts.bn,
          objectName: el.name,
          fit: 'shrink',
          isTextBox: !el.shape
        };
        if (el.bold) opts.bold = true;
        if (native && (el.paragraphs || []).some(p => p.some(r => r.eqSrc))) {
          eqN++;
          eqBoxes[eqN] = el;
          opts.objectName = `${el.name} #qbeq${eqN}`; // marker, removed again in finalize()
        }
        if (el.shape) {
          opts.shape = pres.ShapeType.roundRect;
          opts.rectRadius = el.radius || 0.25;
          opts.fill = { color: el.fill };
          opts.line = { color: el.fill, width: 0 };
        }
        slide.addText(runsToPptx(el.paragraphs, S, el), opts);
      }
      if (sm.notes) slide.addNotes(sm.notes);
    }
    pres._qb = { eqBoxes, S };
    return pres;
  }

  // ------------------------------------------------------------------ native equations
  const NS_MC = 'http://schemas.openxmlformats.org/markup-compatibility/2006';
  const NS_A14 = 'http://schemas.microsoft.com/office/drawing/2010/main';
  const xesc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

  function textRunXml(text, run, kind, el, S) {
    const font = S.fonts[kind] || S.fonts.lat;
    let a = `lang="${kind === 'bn' ? 'bn-BD' : 'en-US'}" sz="${Math.round(el.size * 100)}"`;
    if (run.bold || el.bold) a += ' b="1"';
    if (run.italic) a += ' i="1"';
    if (run.sub) a += ' baseline="-25000"'; else if (run.sup) a += ' baseline="30000"';
    return `<a:r><a:rPr ${a} dirty="0"><a:solidFill><a:srgbClr val="${el.color}"/></a:solidFill>` +
      `<a:latin typeface="${xesc(font)}" charset="0"/><a:ea typeface="${xesc(font)}" charset="0"/><a:cs typeface="${xesc(font)}" charset="0"/></a:rPr>` +
      `<a:t>${xesc(text)}</a:t></a:r>`;
  }

  function paragraphsXml(el, S, pPr) {
    const paras = el.paragraphs && el.paragraphs.length ? el.paragraphs : [[{ text: ' ' }]];
    return paras.map((runs) => {
      let x = '';
      for (let i = 0; i < runs.length;) {
        const r = runs[i];
        if (r.eqSrc) {
          const id = r.eqId;
          let bold = !!(el.bold || r.bold);
          while (i < runs.length && runs[i].eqId === id) i++;
          x += QBOmml.toOMML(r.eqSrc, { sizePt: el.size, color: el.color, bold, fonts: S.fonts });
        } else {
          QBLatex.scriptSegments(r).forEach((seg) => { x += textRunXml(seg.text, r, seg.kind, el, S); });
          i++;
        }
      }
      if (!x) x = textRunXml(' ', {}, 'lat', el, S);
      return `<a:p>${pPr}${x}</a:p>`;
    }).join('');
  }

  function equationShape(sp, el, S) {
    const tb0 = sp.indexOf('<p:txBody>'), tb1 = sp.indexOf('</p:txBody>');
    if (tb0 < 0 || tb1 < 0) return null;
    const body = sp.slice(tb0, tb1);
    const bodyPr = (body.match(/<a:bodyPr[^>]*\/>|<a:bodyPr[^>]*>[\s\S]*?<\/a:bodyPr>/) || [''])[0];
    const lst = (body.match(/<a:lstStyle\/>|<a:lstStyle>[\s\S]*?<\/a:lstStyle>/) || ['<a:lstStyle/>'])[0];
    const pPr = (body.match(/<a:pPr[^>]*\/>|<a:pPr[^>]*>[\s\S]*?<\/a:pPr>/) || [''])[0];
    return sp.slice(0, tb0) + `<p:txBody>${bodyPr}${lst}${paragraphsXml(el, S, pPr)}</p:txBody>` + sp.slice(tb1 + '</p:txBody>'.length);
  }

  /**
   * Writes the presentation and swaps formula text boxes for native PowerPoint equations.
   * Each box becomes mc:AlternateContent — PowerPoint shows the equation version,
   * other apps (LibreOffice, Google Slides, Keynote) show the plain-text fallback.
   * outputType: 'arraybuffer' | 'blob' | 'nodebuffer'
   */
  async function toFile(pres, JSZip, outputType) {
    const info = pres._qb || { eqBoxes: {} };
    const raw = await pres.write({ outputType: 'arraybuffer' });
    if (!Object.keys(info.eqBoxes).length || !JSZip) return convert(raw, outputType, JSZip);
    const zip = await JSZip.loadAsync(raw);
    const slides = Object.keys(zip.files).filter((f) => /^ppt\/slides\/slide\d+\.xml$/.test(f));
    for (const f of slides) {
      let xml = await zip.file(f).async('string');
      if (xml.indexOf('#qbeq') < 0) continue;
      xml = xml.replace(/<p:sp>[\s\S]*?<\/p:sp>/g, (sp) => {
        const m = sp.match(/ #qbeq(\d+)"/);
        if (!m) return sp;
        const clean = sp.replace(` #qbeq${m[1]}"`, '"');
        const el = info.eqBoxes[m[1]];
        const choice = el && equationShape(clean, el, info.S);
        if (!choice) return clean;
        return `<mc:AlternateContent xmlns:mc="${NS_MC}"><mc:Choice xmlns:a14="${NS_A14}" Requires="a14">${choice}</mc:Choice><mc:Fallback>${clean}</mc:Fallback></mc:AlternateContent>`;
      });
      zip.file(f, xml);
    }
    return zip.generateAsync({ type: outputType || 'arraybuffer', compression: 'DEFLATE', mimeType: 'application/vnd.openxmlformats-officedocument.presentationml.presentation' });
  }

  async function convert(buf, outputType, JSZip) {
    if (!outputType || outputType === 'arraybuffer') return buf;
    if (outputType === 'nodebuffer') return Buffer.from(buf);
    if (outputType === 'blob') return new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.presentationml.presentation' });
    return buf;
  }

  return { writeDeck, runsToPptx, toFile };
});
